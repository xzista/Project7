from django.core.management.base import BaseCommand
from menu.models import MenuCategory, Dish


class Command(BaseCommand):
    help = "Loads French cuisine menu with categories and dishes"

    def handle(self, *args, **kwargs):

        self.stdout.write("⏳ Создаём категории...")

        categories = {
            "Закуски": [],
            "Супы": [],
            "Основные блюда": [],
            "Десерты": [],
            "Напитки": [],
        }

        # Создаём категории
        for cat_name in categories.keys():
            cat, created = MenuCategory.objects.get_or_create(name=cat_name)
            categories[cat_name] = cat
            if created:
                self.stdout.write(f"✔ Категория добавлена: {cat_name}")
            else:
                self.stdout.write(f"• Категория уже существует: {cat_name}")

